"""Generate orbita/src/main/res/raw/watchface.xml from the placement of the 3D art.

  python scripts/gen_orbita_xml.py

Sprites and pivots come from art/out/orbita/hand3d_placement.json (scripts/render_3d.sh _ orbita).
Design: docs/superpowers/specs/2026-11-26-orbita-design.md. WFF names checked in docs/pruebas/07-orbita.md.
"""
import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
pl = json.loads((ROOT / "art/out/orbita/hand3d_placement.json").read_text())

GLUCOSE_SLOT, WORKOUT_SLOT = 1, 10
MARKER_ANGLE = "-14 + 68 * clamp([STEP_PERCENT], 0, 100) / 100"
GV = "round([COMPLICATION.RANGED_VALUE_VALUE])"
WHITE, RED, AMBER, GREY, INK = "#fff0f0ec", "#ffe5483c", "#ffe3a63a", "#ff8c8a84", "#ff28282a"
FONT = "barlow_condensed_semibold"
# ring colours fitted to the Blender renders (art/tint_preview.py, docs/pruebas/07-orbita.md)
RING_ARGB = {"verde": "#ff559254", "naranja": "#ffdc6e0b", "rojo": "#ffb10d0b",
             "amarillo": "#ffe7bb0f", "azul": "#ff0d5aac"}
TEXT_R = 213               # radius of the band texts (make_prints.OB_TEXT_R)
STEPS_START = -43          # steps value, clockwise from here (make_prints.OB_STEPS_START)
BATT_START = 214           # battery value, counter-clockwise from here (make_prints.OB_BATT_START)
HR_CENTRE = 149            # heart rate centred here (make_prints.OB_HR_CENTRE)
GLU_X, GLU_Y, GLU_R = 233, 367, 46   # glucose sub-dial (dial centre + (0, 134)), dark disc radius
AMB = '<Variant mode="AMBIENT" target="alpha" value="0" />'


def hand_attrs(n):
    g = pl[n]
    return (f'x="{g["x"]}" y="{g["y"]}" width="{g["width"]}" height="{g["height"]}" '
            f'pivotX="0.5" pivotY="{g["pivot_y"]}"')


def ind(block, n):
    pad = " " * n
    return "\n".join(pad + line if line else line for line in block.splitlines())


def circular(name, expr_template, params, start, end, direction, align, color, ambient_hidden=True):
    """Band text on the circle of radius TEXT_R round the dial centre (TextCircular in a full-frame PartText)."""
    d = 2 * TEXT_R
    pars = "".join(f'<Parameter expression="{p}" />' for p in params)
    body = f"<Template>{expr_template}{pars}</Template>" if params else expr_template  # fixed text: no Template
    return f'''<PartText name="{name}" x="0" y="0" width="466" height="466">
    {AMB if ambient_hidden else ""}
    <TextCircular centerX="233" centerY="233" width="{d}" height="{d}" startAngle="{start}" endAngle="{end}"
        direction="{direction}" align="{align}">
        <Font family="{FONT}" size="28" color="{color}">
            {body}
        </Font>
    </TextCircular>
</PartText>'''


def glucose_value(color, body=None):
    content = body or f'<Template>%s<Parameter expression="{GV}" /></Template>'
    return f'''<PartText x="0" y="18" width="{2 * GLU_R}" height="56">
    <Text align="CENTER">
        <Font family="{FONT}" size="48" color="{color}">{content}</Font>
    </Text>
</PartText>'''


def full_frame(name, resource, extra="", inner=""):
    return (f'<PartImage name="{name}" x="0" y="0" width="466" height="466"{extra}>\n'
            f'    {inner}\n    <Image resource="{resource}" />\n</PartImage>')


def build_xml():
    cap = pl["cap"]
    a = math.radians(-33)
    wx, wy = round(233 + TEXT_R * math.sin(a)), round(233 - TEXT_R * math.cos(a))  # steps zone centre
    ww, wh = 110, 64
    options = "\n".join(f'            <ColorOption id="{i}" displayName="{n}" colors="{c}" />'
                        for i, (n, c) in enumerate(RING_ARGB.items()))
    steps = circular("pasos", "%s", ["[STEP_COUNT]"], STEPS_START, STEPS_START + 40, "CLOCKWISE", "START", INK)
    batt_norm = circular("bateria", "%s%%", ["[BATTERY_PERCENT]"], BATT_START, BATT_START - 32,
                         "COUNTER_CLOCKWISE", "START", INK)
    batt_low = circular("bateria_baja", "%s%%", ["[BATTERY_PERCENT]"], BATT_START, BATT_START - 32,
                        "COUNTER_CLOCKWISE", "START", RED)
    hr = circular("pulso", "%s BPM", ["round([HEART_RATE])"], HR_CENTRE + 22, HR_CENTRE - 22,
                  "COUNTER_CLOCKWISE", "CENTER", INK)
    hr_none = circular("pulso_sin", "-- BPM", [], HR_CENTRE + 22, HR_CENTRE - 22, "COUNTER_CLOCKWISE", "CENTER", INK)
    gx, gy = GLU_X - GLU_R, GLU_Y - GLU_R
    return f'''<?xml version="1.0" encoding="utf-8"?>
<!--
  NVC Orbita, Watch Face Format v2 (Wear OS 5, API 34). GENERATED by scripts/gen_orbita_xml.py.
  Design: docs/superpowers/specs/2026-11-26-orbita-design.md. Coordinates: watch px (466x466).
  Art: scripts/render_3d.sh 256 orbita (Blender) + scripts/sync_face.sh orbita; resources orb_.
  WFF names checked in docs/pruebas/07-orbita.md (STEP_COUNT, STEP_PERCENT, HEART_RATE, TextCircular,
  tintColor with a ColorConfiguration).
-->
<WatchFace width="466" height="466" clipShape="CIRCLE">
    <Metadata key="CLOCK_TYPE" value="ANALOG" />
    <Metadata key="PREVIEW_TIME" value="10:08:37" />

    <UserConfigurations>
        <ColorConfiguration id="colorAnillo" displayName="color_anillo" defaultValue="0">
{options}
        </ColorConfiguration>
    </UserConfigurations>

    <Scene backgroundColor="#ff000000">

        <!-- ===== Dial (Blender, sectors in neutral silver) and Always-On dial ===== -->
{ind(full_frame("fondo", "orb_bg_3d", inner=AMB), 8)}
{ind(full_frame("esfera_ambiente", "orb_ambient_dial", ' alpha="0"', '<Variant mode="AMBIENT" target="alpha" value="255" />'), 8)}

        <!-- ===== Coloured sectors: white anodised layer tinted with the colour chosen in Personalizar ===== -->
{ind(full_frame("anillo", "orb_ring_tint", ' tintColor="[CONFIGURATION.colorAnillo]"', AMB), 8)}

        <!-- ===== Steps progress marker: -14 deg (0 %) .. 54 deg (100 % of the daily goal) ===== -->
        <PartImage name="marca_pasos" x="0" y="0" width="466" height="466" pivotX="0.5" pivotY="0.5">
            {AMB}
            <Transform target="angle" value="{MARKER_ANGLE}" />
            <Image resource="orb_step_marker" />
        </PartImage>

        <!-- ===== Band texts: steps at 10:30 (shoe printed in the dial), battery at 7, pulse at 5 ===== -->
{ind(steps, 8)}
        <Group name="bateria_grupo" x="0" y="0" width="466" height="466">
            {AMB}
            <Condition>
                <Expressions>
                    <Expression name="baja"><![CDATA[[BATTERY_IS_LOW]]]></Expression>
                </Expressions>
                <Compare expression="baja">
{ind(full_frame("pila_baja", "orb_icon_battery_low"), 20)}
{ind(batt_low, 20)}
                </Compare>
                <Default>
{ind(full_frame("pila", "orb_icon_battery"), 20)}
{ind(batt_norm, 20)}
                </Default>
            </Condition>
        </Group>
        <!-- heart rate: 0 means no reading (watch off the wrist): dashes, never "0 BPM" -->
        <Group name="pulso_grupo" x="0" y="0" width="466" height="466">
            {AMB}
            <Condition>
                <Expressions>
                    <Expression name="sin_lectura"><![CDATA[round([HEART_RATE]) == 0]]></Expression>
                </Expressions>
                <Compare expression="sin_lectura">
{ind(hr_none, 20)}
                </Compare>
                <Default>
{ind(hr, 20)}
                </Default>
            </Condition>
        </Group>
        <!-- end heart rate -->

        <!-- ===== One-tap workout: invisible slot over the steps; opens what the user assigns ===== -->
        <ComplicationSlot slotId="{WORKOUT_SLOT}" displayName="Entreno" x="{wx - ww // 2}" y="{wy - wh // 2}"
            width="{ww}" height="{wh}" supportedTypes="MONOCHROMATIC_IMAGE SMALL_IMAGE SHORT_TEXT EMPTY">
            {AMB}
            <DefaultProviderPolicy defaultSystemProvider="EMPTY" defaultSystemProviderType="EMPTY"
                primaryProvider="com.heytap.wearable.sports/com.heytap.wearable.sports.complications.SportFreeTrainingComplicationService"
                primaryProviderType="MONOCHROMATIC_IMAGE" />
            <BoundingBox x="0" y="0" width="{ww}" height="{wh}" />
            <Complication type="MONOCHROMATIC_IMAGE" />
            <Complication type="SMALL_IMAGE" />
            <Complication type="SHORT_TEXT" />
            <Complication type="EMPTY" />
        </ComplicationSlot>

        <!-- ===== Glucose: value only, 48 px, in the sub-dial at 6 (disc r 46 round (233, 367)).
             Colour follows the number shown: < 70 red, > 180 amber, otherwise white. Visible in Always-On. ===== -->
        <ComplicationSlot slotId="{GLUCOSE_SLOT}" displayName="Glucosa" x="{gx}" y="{gy}" width="{2 * GLU_R}"
            height="{2 * GLU_R}" supportedTypes="RANGED_VALUE EMPTY">
            <DefaultProviderPolicy defaultSystemProvider="EMPTY" defaultSystemProviderType="EMPTY"
                primaryProvider="com.gluroo.app/com.gluroo.app.dev.providers.GlucoseRangeDataProviderService"
                primaryProviderType="RANGED_VALUE" />
            <BoundingOval x="0" y="0" width="{2 * GLU_R}" height="{2 * GLU_R}" />
            <Complication type="RANGED_VALUE">
                <Condition>
                    <Expressions>
                        <Expression name="hipo"><![CDATA[{GV} < 70]]></Expression>
                        <Expression name="hiper"><![CDATA[{GV} > 180]]></Expression>
                    </Expressions>
                    <Compare expression="hipo">
{ind(glucose_value(RED), 24)}
                    </Compare>
                    <Compare expression="hiper">
{ind(glucose_value(AMBER), 24)}
                    </Compare>
                    <Default>
{ind(glucose_value(WHITE), 24)}
                    </Default>
                </Condition>
            </Complication>
            <!-- No data: two grey dashes; never a made-up number -->
            <Complication type="EMPTY">
{ind(glucose_value(GREY, "--"), 16)}
            </Complication>
        </ComplicationSlot>

        <!-- ===== Hands (Blender). Shadows: second clock shifted (2, 3) px. Ambient: dim silhouettes. ===== -->
        <AnalogClock x="2" y="3" width="466" height="466">
            {AMB}
            <HourHand resource="orb_hand3d_hour_shadow" {hand_attrs("hour")} />
            <MinuteHand resource="orb_hand3d_minute_shadow" {hand_attrs("minute")} />
            <SecondHand resource="orb_hand3d_second_shadow" {hand_attrs("second")} />
        </AnalogClock>
        <AnalogClock x="0" y="0" width="466" height="466">
            <HourHand resource="orb_hand3d_hour" {hand_attrs("hour")}>
                {AMB}
            </HourHand>
            <HourHand resource="orb_hand3d_hour_aod" {hand_attrs("hour")} alpha="0">
                <Variant mode="AMBIENT" target="alpha" value="255" />
            </HourHand>
            <MinuteHand resource="orb_hand3d_minute" {hand_attrs("minute")}>
                {AMB}
            </MinuteHand>
            <MinuteHand resource="orb_hand3d_minute_aod" {hand_attrs("minute")} alpha="0">
                <Variant mode="AMBIENT" target="alpha" value="255" />
            </MinuteHand>
            <SecondHand resource="orb_hand3d_second" {hand_attrs("second")}>
                {AMB}
            </SecondHand>
        </AnalogClock>
        <PartImage name="tapa_sombra" x="{cap["x"] + 1}" y="{cap["y"] + 2}" width="{cap["width"]}" height="{cap["height"]}">
            {AMB}
            <Image resource="orb_hand3d_cap_shadow" />
        </PartImage>
        <PartImage name="tapa" x="{cap["x"]}" y="{cap["y"]}" width="{cap["width"]}" height="{cap["height"]}">
            {AMB}
            <Image resource="orb_hand3d_cap" />
        </PartImage>

    </Scene>
</WatchFace>
'''


if __name__ == "__main__":
    out = ROOT / "orbita/src/main/res/raw/watchface.xml"
    out.write_text(build_xml(), encoding="utf-8", newline="\n")
    print(out)
